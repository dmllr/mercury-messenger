#!/usr/bin/env python3
import os
import sys
import glob
import re
import xml.etree.ElementTree as ET
from xml.dom import minidom

# Configuration
# Adjust paths relative to the script location
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, '../..'))
SOURCE_DIR = os.path.join(ROOT_DIR, 'src/assets/translations')
ANDROID_RES_DIR = os.path.join(ROOT_DIR, 'src/apps/android/app/src/main/res')

def parse_po_file(file_path):
    """
    Parses a simple .po file and returns a dictionary {msgid: msgstr}.
    Handles multiline strings and comments.
    """
    translations = {}
    current_msgid = []
    current_msgstr = []
    state = None  # None, 'msgid', 'msgstr'

    with open(file_path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue

            # Handle parsing state
            if line.startswith('msgid "'):
                # Save previous
                if current_msgid and current_msgstr:
                    translations[''.join(current_msgid)] = ''.join(current_msgstr)

                # Start new
                state = 'msgid'
                current_msgid = [line[7:-1]] # Remove msgid " and trailing "
                current_msgstr = []
            elif line.startswith('msgstr "'):
                state = 'msgstr'
                current_msgstr = [line[8:-1]] # Remove msgstr " and trailing "
            elif line.startswith('"') and line.endswith('"'):
                # Multiline continuation
                content = line[1:-1]
                if state == 'msgid':
                    current_msgid.append(content)
                elif state == 'msgstr':
                    current_msgstr.append(content)

    # Save last entry
    if current_msgid and current_msgstr:
        translations[''.join(current_msgid)] = ''.join(current_msgstr)

    return translations

def escape_xml_string(value):
    """Escapes characters for Android XML."""
    value = value.replace("'", "\\'")
    value = value.replace('"', '\\"')
    value = value.replace('&', '&amp;')
    value = value.replace('<', '&lt;')
    value = value.replace('>', '&gt;')
    # Handle printf-style formatting if needed, typically %s is fine
    return value

def generate_android_resources():
    if not os.path.exists(SOURCE_DIR):
        print(f"Source directory not found: {SOURCE_DIR}")
        return

    po_files = glob.glob(os.path.join(SOURCE_DIR, '*.po'))
    if not po_files:
        print("No .po files found.")
        return

    print(f"Found {len(po_files)} translation files.")

    for po_file in po_files:
        filename = os.path.basename(po_file)
        lang_code = os.path.splitext(filename)[0]

        translations = parse_po_file(po_file)
        if not translations:
            continue

        # Determine output path
        # en.po -> values/strings.xml
        # ja.po -> values-ja/strings.xml
        if lang_code == 'en':
            values_dir = os.path.join(ANDROID_RES_DIR, 'values')
        else:
            values_dir = os.path.join(ANDROID_RES_DIR, f'values-{lang_code}')

        if not os.path.exists(values_dir):
            os.makedirs(values_dir)

        output_file = os.path.join(values_dir, 'strings-autogenerated.xml')

        # XML Generation
        root = ET.Element('resources')
        # Add comment
        comment = ET.Comment(f" Generated from {filename}. DO NOT EDIT. ")
        root.append(comment)

        for key in sorted(translations.keys()):
            if not key: continue # Skip empty keys (header)

            # Simple validation for valid resource name
            if not re.match(r'^[a-z0-9_]+$', key):
                print(f"Warning: Skipping invalid key '{key}' in {filename}")
                continue

            val = translations[key]
            # Skip empty translations
            if not val: continue

            res_elem = ET.SubElement(root, 'string')
            res_elem.set('name', key)
            res_elem.text = escape_xml_string(val)

        # Write formatted XML
        raw_xml = ET.tostring(root, 'utf-8')
        reparsed = minidom.parseString(raw_xml)
        pretty_xml = reparsed.toprettyxml(indent="    ")

        # Minidom adds extra newlines in text nodes sometimes, simpler to write raw if precise control needed,
        # but for resources pretty print is nicer for debugging.

        with open(output_file, 'w', encoding='utf-8') as f:
            f.write(pretty_xml)

        print(f"Generated: {output_file}")

if __name__ == '__main__':
    generate_android_resources()
